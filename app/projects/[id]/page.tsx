import type { Metadata } from "next";
import { notFound } from "next/navigation";
import { projects, getProject } from "@/lib/projects";
import { siteUrl, authorName, siteName } from "@/lib/site";
import ProjectDetail from "./ProjectDetail";

export function generateStaticParams() {
  return projects.map((project) => ({ id: project.id }));
}

export async function generateMetadata({
  params,
}: {
  params: Promise<{ id: string }>;
}): Promise<Metadata> {
  const { id } = await params;
  const project = getProject(id);

  if (!project) {
    return { title: "Project not found", robots: { index: false, follow: true } };
  }

  return {
    title: project.title,
    description: project.description,
    keywords: [project.client, project.projectType, ...project.technologies],
    alternates: {
      canonical: `/projects/${project.id}`,
    },
    openGraph: {
      title: `${project.title} — ${siteName}`,
      description: project.description,
      url: `/projects/${project.id}`,
      type: "article",
      publishedTime: `${project.date}-01-01T00:00:00.000Z`,
      authors: [authorName],
      tags: project.technologies,
      // og:image is generated by ./opengraph-image.tsx. The raw screenshots are
      // 3400px PNGs up to 8MB, which every scraper rejects outright.
    },
    twitter: {
      card: "summary_large_image",
      title: `${project.title} — ${siteName}`,
      description: project.description,
    },
  };
}

export default async function ProjectDetailPage({
  params,
}: {
  params: Promise<{ id: string }>;
}) {
  const { id } = await params;
  const project = getProject(id);
  if (!project) notFound();

  const structuredData = {
    "@context": "https://schema.org",
    "@type": "CreativeWork",
    "@id": `${siteUrl}/projects/${project.id}#project`,
    name: project.title,
    headline: project.title,
    description: project.longDescription,
    url: `${siteUrl}/projects/${project.id}`,
    image: `${siteUrl}/projects/${project.id}/opengraph-image`,
    dateCreated: project.date,
    genre: project.projectType,
    keywords: project.technologies.join(", "),
    inLanguage: "en-US",
    author: { "@id": `${siteUrl}/#person` },
    creator: { "@id": `${siteUrl}/#person` },
    isPartOf: { "@id": `${siteUrl}/#website` },
    sameAs: [project.url],
    breadcrumb: {
      "@type": "BreadcrumbList",
      itemListElement: [
        { "@type": "ListItem", position: 1, name: authorName, item: siteUrl },
        {
          "@type": "ListItem",
          position: 2,
          name: "Projects",
          item: `${siteUrl}/projects`,
        },
        {
          "@type": "ListItem",
          position: 3,
          name: project.title,
          item: `${siteUrl}/projects/${project.id}`,
        },
      ],
    },
  };

  return (
    <>
      <ProjectDetail id={id} />
      <script
        type="application/ld+json"
        dangerouslySetInnerHTML={{ __html: JSON.stringify(structuredData) }}
      />
    </>
  );
}
